import { expect, test } from '@playwright/test'

test('cancel is previewed, confirmed and restored after refresh', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '不止回答，也能帮你处理。' })).toBeVisible()
  await page.getByRole('button', { name: /帮我取消订单/ }).click()
  const approval = page.getByTestId('approval-card')
  await expect(approval).toBeVisible()
  const orderId = await approval.locator('.approval-target strong').innerText()
  const targetOrder = page.locator('.order-card').filter({ hasText: orderId })
  await expect(approval.getByText('尚未执行')).toBeVisible()
  await page.getByRole('button', { name: '工具轨迹' }).click()
  await expect(page.getByText('核验账户邮箱', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '确认执行', exact: true }).click()
  await expect(approval).toBeHidden()
  await expect(page.getByText(/操作已完成，变更已持久化/)).toBeVisible()
  await page.getByRole('button', { name: '客户与订单' }).click()
  await expect(targetOrder.locator('.status-tag.cancelled')).toBeVisible()
  await page.reload()
  await expect(targetOrder.locator('.status-tag.cancelled')).toBeVisible()
  await expect(page.getByText(/操作已完成，变更已持久化/)).toBeVisible()
  await expect(page.locator('.error-banner')).toHaveCount(0)
})

test('mobile layout and return rejection preserve delivered status', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: /申请商品退货/ }).click()
  await expect(page.getByTestId('approval-card')).toBeVisible()
  const orderId = await page.getByTestId('approval-card').locator('.approval-target strong').innerText()
  await page.getByRole('button', { name: '取消操作', exact: true }).click()
  await expect(page.getByText('已取消本次操作，数据未变更。')).toBeVisible()
  await expect(page.locator('.order-card').filter({ hasText: orderId }).locator('.status-tag.delivered')).toBeVisible()
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  expect(overflow).toBe(false)
  await page.getByRole('button', { name: '发起新咨询', exact: true }).click()
  await expect(page.getByRole('heading', { name: '不止回答，也能帮你处理。' })).toBeVisible()
})
